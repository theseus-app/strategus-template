################################################################################
# CreateStrategusAnalysisSpecification.R
# 
# This script creates analysis specifications for a comparative cohort study
# comparing ticagrelor vs clopidogrel using the OHDSI Strategus framework.
#
# Study Name: ticagrelorclopidogrel
# Target Cohort: target1 (ID: 1794126)
# Comparator Cohort: comparator1 (ID: 1794132)
# Outcome Cohort: outcome1 (ID: 1794131)
# Negative Control Concept Set: negative (ID: 1888110)
#
# Study Period: 2011-11-01 to 2019-03-31
# Washout Period: 365 days
# Time-at-Risk: Day 1 to Day 365 from cohort start
# PS Adjustment: 1:1 matching with caliper 0.2 on standardized logit scale
# Outcome Model: Cox proportional hazards (unstratified)
#
# See the Create analysis specifications section
# of the UsingThisTemplate.md for more details.
# 
# More information about Strategus HADES modules can be found at:
# https://ohdsi.github.io/Strategus/reference/index.html#omop-cdm-hades-modules.
# This help page also contains links to the corresponding HADES package that
# further details.
################################################################################

library(dplyr)
library(Strategus)

# Shared Resources -------------------------------------------------------------
# Get the list of cohorts from ATLAS WebAPI
baseUrl <- "https://atlas-demo.ohdsi.org/WebAPI"

# Cohort Definitions
# Export cohort definitions for target, comparator, and outcome cohorts
# Target: target1 (ID: 1794126)
# Comparator: comparator1 (ID: 1794132)
# Outcome: outcome1 (ID: 1794131)
cohortDefinitionSet <- ROhdsiWebApi::exportCohortDefinitionSet(
  baseUrl = baseUrl,
  cohortIds = c(
    1794126, # Target: target1
    1794132, # Comparator: comparator1
    1794131 # Outcome: outcome1
  ),
  generateStats = TRUE
)

# Re-number cohorts for internal use
# This ensures consistent cohort IDs across the analysis
cohortDefinitionSet[cohortDefinitionSet$cohortId == 1794126,]$cohortId <- 1
cohortDefinitionSet[cohortDefinitionSet$cohortId == 1794132,]$cohortId <- 2
cohortDefinitionSet[cohortDefinitionSet$cohortId == 1794131,]$cohortId <- 3

# Negative control outcomes
# Retrieve negative control concepts from the concept set defined in ATLAS
# Concept Set ID: 1888110 (name: negative)
negativeControlOutcomeCohortSet <- ROhdsiWebApi::getConceptSetDefinition(
  conceptSetId = 1888110,
  baseUrl = baseUrl
) %>%
  ROhdsiWebApi::resolveConceptSet(
    baseUrl = baseUrl
  ) %>%
  ROhdsiWebApi::getConcepts(
    baseUrl = baseUrl
  ) %>%
  rename(outcomeConceptId = "conceptId",
         cohortName = "conceptName") %>%
  mutate(cohortId = row_number() + 100) %>% # target/comparator cohort ids start with 1, 2, 3... negativeControl -> 101, 102, 103...
  select(cohortId, cohortName, outcomeConceptId)

# Validate that there are no duplicate cohort IDs between main cohorts and negative controls
if (any(duplicated(cohortDefinitionSet$cohortId, negativeControlOutcomeCohortSet$cohortId))) {
  stop("*** Error: duplicate cohort IDs found ***")
}

# Create some data frames to hold the cohorts we'll use in each analysis ---------------

# Outcomes: outcome1
# cleanWindow set to 365 days based on priorOutcomeLookBack setting
oList <- cohortDefinitionSet %>%
  filter(.data$cohortId == 3) %>%
  mutate(outcomeCohortId = cohortId, outcomeCohortName = cohortName) %>%
  select(outcomeCohortId, outcomeCohortName) %>%
  mutate(cleanWindow = 365)

# Target and Comparator for the CohortMethod analysis 
# Target: target1 (renumbered to ID 1)
# Comparator: comparator1 (renumbered to ID 2)
cmTcList <- data.frame(
  targetCohortId = 1,
  targetCohortName = "target1",
  comparatorCohortId = 2,
  comparatorCohortName = "comparator1"
)

# For the CohortMethod LSPS we'll need to exclude the drugs of interest in this
# study. Note: No specific concepts to exclude were provided in the specifications
# (conceptsToExclude id is null), so this is left empty but the structure is maintained
excludedCovariateConcepts <- data.frame(
  conceptId = c(),
  conceptName = c()
)

# Optional: If you want to define covariates to include instead of including them all
# Note: No specific concepts to include were provided in the specifications
# (conceptsToInclude id is null)
# includedCovariateConcepts <- data.frame(
